const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const { normalizeShop, imageUrl, shouldReplaceSnapshot } = require('./fetch-shop.cjs');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
const shop = require('../src/lib/shop.ts');
const fetched = '2026-11-06T03:00:00.000Z';
const rawEntry = { offerId: 'offer-1', finalPrice: 500, regularPrice: 800, inDate: '2026-11-06T00:00:00Z', outDate: '2026-11-07T00:00:00Z', layout: { name: 'Music', index: 0, rank: 5 }, tracks: [{ title: 'Test Song', artist: 'Test Artist', albumArt: 'https://cdn.fortnite-api.com/test.jpg' }] };
const payload = entries => ({ status: 200, data: { date: '2026-11-06T00:00:00Z', entries } });
const first = normalizeShop(payload([rawEntry]), fetched);
assert.equal(first.entries[0].name, 'Test Song');
assert.equal(first.entries[0].types[0], 'Jam Track');
assert.equal(first.entries[0].items[0].artist, 'Test Artist');
assert.equal(first.entries[0].image, 'https://cdn.fortnite-api.com/test.jpg');
assert.equal(first.sourceDate, '2026-11-06T00:00:00.000Z');
assert.equal(first.fetchedAt, fetched);
assert.throws(() => normalizeShop(payload([]), fetched), /Empty/);
assert.throws(() => normalizeShop(payload([rawEntry, rawEntry]), fetched), /duplicate/);
assert.throws(() => normalizeShop(payload([{ ...rawEntry, finalPrice: -1 }]), fetched), /Invalid/);
assert.throws(() => normalizeShop(payload([{ ...rawEntry, tracks: undefined }]), fetched), /Unrecognized/);
assert.throws(() => normalizeShop(payload([{ ...rawEntry, futureFamily: [{ name: 'Unmapped item' }] }]), fetched), /Unrecognized offer array/);
assert.throws(() => normalizeShop(payload([rawEntry]), '2026-11-05T03:00:00Z'), /future/);
assert.throws(() => normalizeShop(payload([{ ...rawEntry, outDate: '2026-11-05T00:00:00Z' }]), fetched), /interval/);
assert.equal(imageUrl('javascript:alert(1)'), null);
assert.equal(imageUrl('https://fortnite-api.com.evil.example/image.png'), null);
assert.equal(imageUrl('http://fortnite-api.com/image.png'), null);
assert.equal(shouldReplaceSnapshot(first, { ...first, fetchedAt: '2026-11-06T04:00:00Z' }), false);
assert.equal(shouldReplaceSnapshot(null, first), true);
assert.equal(shouldReplaceSnapshot(first, { ...first, sourceDate: '2026-11-07T00:00:00.000Z' }), true);
assert.throws(() => shouldReplaceSnapshot(first, { ...first, sourceDate: '2026-11-05T00:00:00.000Z' }), /older shop/);
const mixed = normalizeShop(payload([{ ...rawEntry, bundle: { name: 'Mixed Bundle' }, brItems: [{ name: 'Outfit', type: { displayValue: 'Outfit' } }], cars: [{ name: 'Car', images: { large: 'https://fortnite-api.com/car.png' } }], instruments: [{ name: 'Guitar' }], legoKits: [{ name: 'Build' }] }]), fetched);
assert.equal(mixed.entries[0].items.length, 5);
assert.equal(mixed.entries[0].name, 'Mixed Bundle');
assert.equal(mixed.entries[0].isBundle, true);
assert.equal(shop.filterShop(first.entries, { ...shop.emptyShopFilters, query: 'TEST ARTIST' }).length, 1);
assert.equal(shop.filterShop(first.entries, { ...shop.emptyShopFilters, query: 'absent' }).length, 0);
assert.equal(shop.filterShop(first.entries, { ...shop.emptyShopFilters, budget: '400' }).length, 0);
assert.equal(shop.filterShop(first.entries, { ...shop.emptyShopFilters, budget: '500', discounted: true }).length, 1);
assert.equal(shop.filterShop(mixed.entries, { ...shop.emptyShopFilters, type: 'Bundle' }).length, 1);
assert.equal(shop.filterShop(first.entries, { ...shop.emptyShopFilters, section: 'Other' }).length, 0);
assert.equal(shop.snapshotIsStale(first.sourceDate, Date.parse('2026-11-06T23:59:59Z')), false);
assert.equal(shop.snapshotIsStale(first.sourceDate, Date.parse('2026-11-07T00:00:00Z')), true);
assert.equal(shop.nextUtcReset(Date.parse('2026-12-31T23:59:00Z')), Date.parse('2027-01-01T00:00:00Z'));
assert.equal(shop.offerTiming(first.entries[0], Date.parse('2026-11-07T00:00:00Z')), 'Listed removal time has passed');
assert.match(shop.offerTiming(first.entries[0], Date.parse('2026-11-06T23:59:01Z')), /^0h 1m/);
assert.match(shop.offerTiming(first.entries[0], null), /^Listed until/);
const real = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../src/data/item-shop.json'), 'utf8'));
assert.ok(real.entries.length > 0 && real.entries.length <= 5000);
assert.equal(new Set(real.entries.map(item => item.id)).size, real.entries.length);
assert.ok(real.entries.every(item => item.name && Number.isInteger(item.finalPrice) && item.finalPrice >= 0 && (!item.image || imageUrl(item.image))));
const sorted = shop.filterShop(real.entries, { ...shop.emptyShopFilters, sort: 'price-asc' });
assert.ok(sorted.every((entry, index) => index === 0 || entry.finalPrice >= sorted[index - 1].finalPrice));
console.log(`Shop normalization, unsafe-data rejection, filters, sorting and UTC boundaries passed; ${real.entries.length} saved offers validated.`);
